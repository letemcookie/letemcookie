CREATE TABLE IF NOT EXISTS totals (id INTEGER PRIMARY KEY CHECK(id=1), eaten INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO totals(id,eaten) VALUES(1,0);
CREATE TABLE IF NOT EXISTS daily (day TEXT PRIMARY KEY, eaten INTEGER NOT NULL DEFAULT 0, connections INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS clients (day TEXT NOT NULL, hash TEXT NOT NULL, eaten INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(day,hash));
CREATE TABLE IF NOT EXISTS events (id TEXT PRIMARY KEY, day TEXT NOT NULL, hash TEXT NOT NULL, received INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS events_received ON events(received);
CREATE TRIGGER IF NOT EXISTS cap_event BEFORE INSERT ON events
WHEN COALESCE((SELECT eaten FROM clients WHERE day=NEW.day AND hash=NEW.hash),0)>=500
BEGIN SELECT RAISE(IGNORE); END;
CREATE TRIGGER IF NOT EXISTS count_event AFTER INSERT ON events BEGIN
  UPDATE totals SET eaten=eaten+1 WHERE id=1;
  INSERT INTO daily(day,eaten,connections) VALUES(NEW.day,1,1)
  ON CONFLICT(day) DO UPDATE SET eaten=eaten+1,connections=connections+CASE WHEN EXISTS(SELECT 1 FROM clients WHERE day=NEW.day AND hash=NEW.hash) THEN 0 ELSE 1 END;
  INSERT INTO clients(day,hash,eaten) VALUES(NEW.day,NEW.hash,1)
  ON CONFLICT(day,hash) DO UPDATE SET eaten=eaten+1;
END;
